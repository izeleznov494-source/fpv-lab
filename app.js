const readerTitle = document.getElementById('reader-title');
const readerContent = document.getElementById('reader-content');

function render(items, container) {
    items.forEach(item => {
        if (item.children) {
            const folder = document.createElement('div');
            folder.className = 'folder';
            
            const header = document.createElement('div');
            header.className = 'folder-header';
            header.innerHTML = `<span>📁</span><span>${item.title}</span><span class="arrow">▶</span>`;
            
            const content = document.createElement('div');
            content.className = 'folder-content';
            
            header.addEventListener('click', () => {
                folder.classList.toggle('open');
                if(!folder.classList.contains('open')) {
                    content.style.maxHeight = null;
                } else {
                    content.style.maxHeight = content.scrollHeight + "px";
                }
            });
            
            folder.appendChild(header);
            folder.appendChild(content);
            container.appendChild(folder);
            
            const childrenObjects = item.children.map(title => ({ title }));
            render(childrenObjects, content);
        } else {
            const doc = document.createElement('div');
            doc.className = 'doc';
            doc.innerHTML = `<span>📄</span> <span>${item.title}</span>`;
            doc.addEventListener('click', () => {
                const text = texts[item.title] || "Текст лекции пока не добавлен.";
                openReader(item.title, text);
            });
            container.appendChild(doc);
        }
    });
}

function openReader(title, text) {
    readerTitle.textContent = title;
    readerContent.innerHTML = text.replace(/\n/g, '<br><br>'); 
    
    mainHeader.classList.add('hidden');
    appContainer.classList.add('hidden');
    readerView.classList.remove('hidden');
    window.scrollTo(0, 0);
}

function closeReader() {
    mainHeader.classList.remove('hidden');
    appContainer.classList.remove('hidden');
    readerView.classList.add('hidden');
}

